export function sanitizeLicensePlate(input: string): string {
  if (!input) return '';
  return input
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '')
    .trim();
}

export function validateLicensePlateFormat(plate: string): { valid: boolean; reason?: string } {
  if (!plate || plate.length < 2) {
    return { valid: false, reason: 'License plate must be at least 2 characters long.' };
  }
  if (plate.length > 10) {
    return { valid: false, reason: 'License plate must not exceed 10 characters.' };
  }
  return { valid: true };
}